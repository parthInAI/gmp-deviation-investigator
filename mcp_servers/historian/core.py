"""Process historian: read-only views of a batch's sensor data, the frozen detector's alarm, and
how each signal compares with the normal batches at the same process time.

Everything here is a plain function so it can be tested without an MCP transport; server.py
exposes them as MCP tools. Three rules:

1. Read-only. Nothing here writes data.
2. No labels. The simulator's fault columns never leave this module: the agents investigate
   from the same signals a plant would have, and the eval answer key stays out of reach.
3. One reference. "Normal" means the frozen Phase 3 detector's time profile (60 training
   batches, per process step), the same reference that raised the alarm, so the alarm, the
   comparison and the citation check all agree with each other.

Sensor citations have one form, used by the report writer and checked by the evals:

    SENSOR:<batch>:<signal>:<start_h>-<end_h>      e.g. SENSOR:94:aeration_rate_lph:20.0-24.0
"""

from __future__ import annotations

import json
import os
import re
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

import numpy as np
import pandas as pd

from models.data import MONITORED, load_readings
from models.detector import ARTIFACT_DIR, Detector
from models.evaluate import norm_score
from models.features import smooth_causal

HERE = Path(__file__).parent
LABEL_COLUMNS = ("fault_ref", "fault_flag")
Z_OUT = 3.0  # |z| above this = outside the normal band
SUSTAIN = 3  # readings (0.6 h) outside the band before it counts as a departure
CITE = re.compile(r"^SENSOR:(\d+):([a-z0-9_]+):(\d+(?:\.\d+)?)-(\d+(?:\.\d+)?)$")

SIGNALS = {
    "aeration_rate_lph": ("L/h", "sterile air flow into the fermenter"),
    "sugar_feed_rate_lph": ("L/h", "substrate (sugar) feed rate"),
    "acid_flow_rate_lph": ("L/h", "acid dosing for pH control"),
    "base_flow_rate_lph": ("L/h", "base dosing for pH control"),
    "cooling_water_flow_lph": ("L/h", "cooling water through the jacket"),
    "heating_water_flow_lph": ("L/h", "heating water through the jacket"),
    "air_head_pressure_bar": ("bar", "vessel head pressure"),
    "dissolved_oxygen_mgpl": ("mg/L", "dissolved oxygen in the broth"),
    "vessel_volume_l": ("L", "broth volume"),
    "vessel_weight_kg": ("kg", "vessel weight"),
    "ph": ("pH", "online pH"),
    "temperature_k": ("K", "broth temperature"),
    "generated_heat_kj": ("kJ", "heat generated by the culture"),
    "offgas_co2_pct": ("%", "CO2 in the exhaust gas"),
    "offgas_o2_pct": ("fraction", "O2 in the exhaust gas"),
    "paa_flow_lph": ("L/h", "phenylacetic acid precursor feed"),
    "oil_flow_lph": ("L/h", "soybean oil feed"),
    "oxygen_uptake_rate": ("g/min", "oxygen uptake rate (from off-gas)"),
    "carbon_evolution_rate": ("g/h", "carbon dioxide evolution rate (from off-gas)"),
}


def source() -> str:
    return os.environ.get("HISTORIAN_SOURCE", "/lakehouse/silver/process_sensor")


@lru_cache(maxsize=1)
def detector() -> Detector:
    return Detector.load(ARTIFACT_DIR / "pca")


def _from_databricks(table: str) -> pd.DataFrame:
    """Read the silver table through a Databricks SQL warehouse (DATABRICKS_HOST, DATABRICKS_HTTP_PATH,
    DATABRICKS_TOKEN). Same columns and order as load_readings; labels are never selected."""
    from databricks import sql  # optional: pip install databricks-sql-connector

    from models.data import FEATURES

    cols = ", ".join(["batch_id", "seq", "time_h", *FEATURES])
    with (
        sql.connect(
            server_hostname=os.environ["DATABRICKS_HOST"].removeprefix("https://"),
            http_path=os.environ["DATABRICKS_HTTP_PATH"],
            access_token=os.environ["DATABRICKS_TOKEN"],
        ) as conn,
        conn.cursor() as cur,
    ):
        cur.execute(f"SELECT {cols} FROM {table} ORDER BY batch_id, seq")  # noqa: S608 (table name from config)
        df = cur.fetchall_arrow().to_pandas()
    df["step"] = (df["time_h"] / 0.2).round().astype(int)  # same as models.data.load_readings
    return df


@lru_cache(maxsize=1)
def readings(src: str | None = None) -> pd.DataFrame:
    """All readings, labels removed. src: a silver Delta dir, the IndPenSim CSV, or
    databricks:<catalog>.<schema>.silver_process_sensor (e.g. databricks:workspace.gmpdi.silver_process_sensor)."""
    src = src or source()
    df = _from_databricks(src.removeprefix("databricks:")) if src.startswith("databricks:") else load_readings(src)
    return df.drop(columns=[c for c in LABEL_COLUMNS if c in df.columns]).reset_index(drop=True)


@lru_cache(maxsize=1)
def confidence_bands() -> list[dict]:
    return json.loads((HERE / "confidence.json").read_text())["bands"]


def batch(batch_id: int) -> pd.DataFrame:
    df = readings()
    b = df[df.batch_id == int(batch_id)].sort_values("seq").reset_index(drop=True)
    if b.empty:
        raise ValueError(f"no readings for batch {batch_id}")
    return b


def _z(frame: pd.DataFrame) -> np.ndarray:
    det = detector()
    return det.profile.transform(smooth_causal(frame, det.features, det.smooth_window))


def _runs(mask: np.ndarray) -> list[tuple[int, int]]:
    out, i = [], 0
    while i < len(mask):
        if mask[i]:
            j = i
            while j + 1 < len(mask) and mask[j + 1]:
                j += 1
            out.append((i, j))
            i = j + 1
        else:
            i += 1
    return out


def confidence(multiple: float) -> dict:
    """Share of readings that were truly faulty at this score level on the held-out Phase 3 test."""
    for b in confidence_bands():
        if b["low"] <= multiple < b["high"]:
            return {"score_band": b["label"], "historical_fault_share": b["fault_share"]}
    return {"score_band": "unknown", "historical_fault_share": None}


# ---------------------------------------------------------------- tools


def list_signals() -> list[dict]:
    return [{"signal": s, "unit": u, "meaning": m} for s, (u, m) in SIGNALS.items() if s in MONITORED]


def batch_overview(batch_id: int) -> dict:
    b = batch(batch_id)
    det = detector()
    return {
        "batch_id": int(batch_id),
        "readings": len(b),
        "duration_h": round(float(b.time_h.max()), 1),
        "reading_interval_h": 0.2,
        "normal_reference_covers_until_h": round(det.profile.last_reliable * 0.2, 1),
        "signals": len(MONITORED),
    }


def get_alarm(batch_id: int, contributors: int = 5) -> dict:
    """The frozen detector's verdict on a batch: alarm periods, the first alarm, what drove it, confidence."""
    b = batch(batch_id)
    det = detector()
    stats = det.statistics(b)
    score = norm_score(det, stats)
    alarm = det.alarm(b, stats)
    periods = [
        {
            "start_h": round(float(b.time_h[i]), 1),
            "end_h": round(float(b.time_h[j]), 1),
            "peak_score_x_limit": round(float(score[i : j + 1].max()), 2),
        }
        for i, j in _runs(alarm)
    ]
    out = {
        "batch_id": int(batch_id),
        "detector": "gmpdi-fault-detector v1 (PCA, Hotelling T2 + SPE, frozen, SHA-256 checked)",
        "alarm": bool(periods),
        "alarm_periods": periods,
    }
    if not periods:
        return out
    first = int(np.argmax(alarm))
    t_alarm = float(b.time_h[first])
    window = b.time_h.between(t_alarm - 2.0, t_alarm).to_numpy()
    contrib = det.contributions(b)[window].mean()
    share = (contrib / contrib.sum()).sort_values(ascending=False).head(contributors)
    peak = float(score[window].max())
    out.update(
        {
            "first_alarm_h": round(t_alarm, 1),
            "top_contributing_signals": [{"signal": s, "share_of_score": round(float(v), 3)} for s, v in share.items()],
            "peak_score_x_limit_before_alarm": round(peak, 2),
            "confidence": confidence(peak),
            "note": "An alarm says the batch left its normal pattern for 2 h. It does not say why.",
        }
    )
    return out


def get_trend(batch_id: int, signals: list[str], start_h: float, end_h: float, every: int = 5) -> dict:
    """Raw values of chosen signals over a window, every `every`-th reading (default: hourly)."""
    bad = [s for s in signals if s not in MONITORED]
    if bad:
        raise ValueError(f"unknown signals {bad}; call list_signals")
    b = batch(batch_id)
    w = b[b.time_h.between(start_h, end_h)].iloc[:: max(1, int(every))]
    return {
        "batch_id": int(batch_id),
        "rows": [
            {"time_h": round(float(t), 1), **{s: round(float(w[s].iloc[i]), 4) for s in signals}}
            for i, t in enumerate(w.time_h)
        ],
    }


def compare_to_normal(batch_id: int, start_h: float, end_h: float, signals: list[str] | None = None) -> dict:
    """Each signal against the normal batches at the same process time, ordered by which left its band first."""
    det = detector()
    feats = list(det.features)
    signals = [s for s in (signals or feats) if s in feats]
    b = batch(batch_id)
    z = _z(b)
    cov = det.profile.in_coverage(b)
    win = (b.time_h.between(start_h, end_h).to_numpy()) & cov
    rows = det.profile._rows(b.step.to_numpy())
    out = []
    for s in signals:
        k = feats.index(s)
        zs = np.where(win, z[:, k], 0.0)
        outside = np.abs(zs) > Z_OUT
        first = next(((i, j) for i, j in _runs(outside) if j - i + 1 >= SUSTAIN), None)
        rec = {
            "signal": s,
            "max_abs_z": round(float(np.abs(zs).max()), 2),
            "first_left_normal_band_h": round(float(b.time_h[first[0]]), 1) if first else None,
            "direction": ("above" if z[first[0], k] > 0 else "below") if first else None,
        }
        if first:
            i = first[0]
            rec["value_then"] = round(float(b[s][i]), 4)
            rec["normal_mean_then"] = round(float(det.profile.mean[rows[i], k]), 4)
        out.append(rec)
    left = [r for r in out if r["first_left_normal_band_h"] is not None]
    moved = sorted(left, key=lambda r: (r["first_left_normal_band_h"], -r["max_abs_z"]))
    quiet = sorted([r for r in out if r["first_left_normal_band_h"] is None], key=lambda r: -r["max_abs_z"])
    return {
        "batch_id": int(batch_id),
        "window_h": [start_h, end_h],
        "normal_band": f"|z| <= {Z_OUT} against the 60 training batches at the same process step",
        "left_band_in_order": moved,
        "stayed_in_band": [r["signal"] for r in quiet],
    }


# ---------------------------------------------------------------- citations


@dataclass
class CitationCheck:
    valid: bool
    reason: str


def check_sensor_citation(cite: str) -> CitationCheck:
    """Valid if the batch, signal and window exist and the signal is outside its normal band in that window."""
    m = CITE.match(cite.strip())
    if not m:
        return CitationCheck(False, "not in the form SENSOR:<batch>:<signal>:<start_h>-<end_h>")
    bid, sig, a, e = int(m.group(1)), m.group(2), float(m.group(3)), float(m.group(4))
    if sig not in detector().features:
        return CitationCheck(False, f"unknown signal {sig}")
    if e <= a:
        return CitationCheck(False, "window end is not after its start")
    try:
        b = batch(bid)
    except ValueError:
        return CitationCheck(False, f"no batch {bid}")
    if a < 0 or e > float(b.time_h.max()) + 0.2:
        return CitationCheck(False, "window outside the batch")
    z = _z(b)[:, list(detector().features).index(sig)]
    w = b.time_h.between(a, e).to_numpy() & detector().profile.in_coverage(b)
    if not w.any():
        return CitationCheck(False, "window has no readings inside the normal reference coverage")
    peak = float(np.abs(z[w]).max())
    if peak <= Z_OUT:
        return CitationCheck(False, f"{sig} stays inside its normal band in that window (max |z| {peak:.1f})")
    return CitationCheck(True, f"{sig} outside its normal band (max |z| {peak:.1f})")
